const mongoose = require("mongoose");

const userSchema=new mongoose.Schema(
    {
        fullName:{
            type:String,
            required:true,
            trim:true
        },
        email:{
            type:String,
            required:true,
            unique:true,
            lowercase:true,
            trim:true
        },
        passwordHash:{
            type:String,
             required:true
        },
        role:{
            type:String,
            required:true,
            default:"user"
        },
        isVerified:{
            type:Boolean,
            default:false
        },
        profileImage:{
            type:String,
            default:null
        },
        referralCode:{
            type:String,
            unique:true,
            sparse:true
        },
        status:{
            type:String,
            required:true,
            default:"active"
        }
    },
    {
        timestamps:true
    }
);
module.exports=mongoose.model("User", userSchema);
